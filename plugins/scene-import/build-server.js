"use strict";
const fs = require("node:fs");
const path = require("node:path");
// The embedded runtime is synchronous. Native job waits yield to queued continuations.
const source = fs.readFileSync(path.join(__dirname, "scene-import.js"), "utf8").split("  function createController(")[0];
const core = source.replace(/\basync /g, "").replace(/\bawait /g, "")
  .replace('const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));', 'const sleep = (ms) => util.Sleep(ms);');
const worker = fs.readFileSync(path.join(__dirname, "server.js"), "utf8");
const output = '// Generated by node build-server.js; edit scene-import.js and server.js.\nconst core = ' + core
  + '  return { run, refreshRows };\n})(globalThis);\n' + worker
  + '\n({ Output: server(core, (query, variables = {}) => gql.Do(query, variables), input.Args || {}, (message) => log.Info(message), (ms) => util.Sleep(ms)) });\n';
const target = path.join(__dirname, "scene-import-server.js");
if (process.argv.includes("--check")) require("node:assert/strict").equal(fs.readFileSync(target, "utf8"), output, "Run node build-server.js");
else fs.writeFileSync(target, output);
